#!/usr/bin/env bash
set -euo pipefail

# ------------------------------------------------------------
# Runtime bootstrap
# ------------------------------------------------------------
source "${SCRIPT_LIB_DIR}/runtime.sh"
source "${SCRIPT_LIB_DIR}/common.sh"

require_root

log "Configuring OpenDKIM"

# ------------------------------------------------------------
# Required environment
# ------------------------------------------------------------
: "${MAIL_DOMAIN:?MAIL_DOMAIN not set}"
: "${MAIL_HOSTNAME:?MAIL_HOSTNAME not set}"
: "${DKIM_SELECTOR:?DKIM_SELECTOR not set}"

# ------------------------------------------------------------
# Paths
# ------------------------------------------------------------
OPENDKIM_DIR="/etc/opendkim"
KEY_DIR="${OPENDKIM_DIR}/keys/${MAIL_DOMAIN}"

mkdir -p "$KEY_DIR"

# ------------------------------------------------------------
# Generate DKIM key
# ------------------------------------------------------------
log "Generating DKIM keys"

opendkim-genkey \
    -D "$KEY_DIR" \
    -d "$MAIL_DOMAIN" \
    -s "$DKIM_SELECTOR"

chown -R opendkim:opendkim "$OPENDKIM_DIR"

chmod 600 "${KEY_DIR}/${DKIM_SELECTOR}.private"

# ------------------------------------------------------------
# Configure signing tables
# ------------------------------------------------------------
log "Configuring signing tables"

cat > "${OPENDKIM_DIR}/KeyTable" <<EOF
${DKIM_SELECTOR}._domainkey.${MAIL_DOMAIN} ${MAIL_DOMAIN}:${DKIM_SELECTOR}:${KEY_DIR}/${DKIM_SELECTOR}.private
EOF

cat > "${OPENDKIM_DIR}/SigningTable" <<EOF
*@${MAIL_DOMAIN} ${DKIM_SELECTOR}._domainkey.${MAIL_DOMAIN}
EOF

cat > "${OPENDKIM_DIR}/TrustedHosts" <<EOF
127.0.0.1
localhost
${MAIL_HOSTNAME}
EOF

# ------------------------------------------------------------
# Main OpenDKIM configuration
# ------------------------------------------------------------
log "Writing OpenDKIM configuration"

cat > "${OPENDKIM_DIR}/opendkim.conf" <<EOF
Syslog                  yes
UMask                   002

Canonicalization        relaxed/simple
Mode                    sv
SubDomains              no

Socket                  inet:8891@localhost

KeyTable                ${OPENDKIM_DIR}/KeyTable
SigningTable            ${OPENDKIM_DIR}/SigningTable
TrustedHosts            ${OPENDKIM_DIR}/TrustedHosts
EOF

# ------------------------------------------------------------
# Restart service
# ------------------------------------------------------------
log "Restarting OpenDKIM"

systemctl enable opendkim
systemctl restart opendkim

# ------------------------------------------------------------
# Verify service
# ------------------------------------------------------------
log "Verifying OpenDKIM"

systemctl is-active --quiet opendkim || {
    log "OpenDKIM failed to start"
    exit 1
}

# ------------------------------------------------------------
# Extract DNS record
# ------------------------------------------------------------
log "Extracting DKIM DNS record"

DNS_RECORD=$(sed -n '/TXT/,$p' "${KEY_DIR}/${DKIM_SELECTOR}.txt" \
    | sed 's/.*TXT[[:space:]]*(//' \
    | sed 's/).*//' \
    | tr -d '"' \
    | tr -d '\n' \
    | sed 's/[[:space:]]\+/ /g')

echo
echo "======================================================"
echo "DKIM DNS record (copy into your DNS provider)"
echo "======================================================"
echo

echo "Original file generated by OpenDKIM"
echo "-----------------------------------"
cat "${KEY_DIR}/${DKIM_SELECTOR}.txt"
echo
echo "-----------------------------------"
echo

echo "DNS fields for provider"
echo "-----------------------"
echo

echo "Type"
echo "TXT"
echo

echo "Name"
echo "${DKIM_SELECTOR}._domainkey"
echo

echo "Content"
echo "\"${DNS_RECORD}\""
echo

echo "======================================================"

log "OpenDKIM configured successfully"

echo "opendkim_configured=true"
echo "mail_domain=${MAIL_DOMAIN}"
echo "mail_hostname=${MAIL_HOSTNAME}"